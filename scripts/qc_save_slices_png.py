"""
Save slices in PNG format from the format .npy generated by the slices pipeline (Quality Control).

Examples:
    # Save the coronal slices of subject ADNI002S0295, session m060, experiment anat::
    python scripts/visualize_slices.py --sub ADNI002S0295 --ses m060 --experiment anat --view coronal
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

DEFAULT_ROOT = Path(
    "/pool/home/AD_Multimodal/PREVENT-AD/Folder_Noa/derivatives/admri/slices"
)


def find_slices(root: Path, experiment: str, sub: str, ses: str, view: str) -> list[Path]:
    folder = root / experiment / f"sub-{sub}" / f"ses-{ses}" / "anat"
    if not folder.exists():
        raise FileNotFoundError(f"Folder not found: {folder}")
    files = sorted(folder.glob(f"*_view-{view}_*.npy"))
    if not files:
        raise FileNotFoundError(f"No .npy files found with view-{view} in {folder}")
    return files


def slice_label(path: Path) -> str:
    # 'sub-..._slice-108_view-coronal_T1w.npy' -> 'slice 108'
    for part in path.stem.split("_"):
        if part.startswith("slice-"):
            return part.replace("-", " ")
    return path.stem


def plot_slices(files: list[Path], title: str, rotate: bool = True) -> plt.Figure:
    fig, axes = plt.subplots(1, len(files), figsize=(4 * len(files), 4.5), squeeze=False)
    for ax, f in zip(axes[0], files):
        img = np.load(f)
        print(f"{f.name}: shape={img.shape}, dtype={img.dtype}, "f"min={img.min():.3f}, max={img.max():.3f}")
        ax.imshow(np.rot90(img) if rotate else img, cmap="gray")
        ax.set_title(slice_label(f))
        ax.axis("off")
    fig.suptitle(title)
    fig.tight_layout()
    return fig


def main() -> None:
    p = argparse.ArgumentParser(description="QC visual of the .npy slices")
    p.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="Folder 'slices'")
    p.add_argument("--experiment", required=True, help="Subfolder of the experiment (e.g., anat)")
    p.add_argument("--sub", required=True, help="Subject ID, without 'sub-'")
    p.add_argument("--ses", required=True, help="Session, without 'ses-'")
    p.add_argument("--view", default="coronal", choices=["coronal", "axial", "sagittal"])
    p.add_argument("--no-rotate", action="store_true", help="No rotar les imatges")
    args = p.parse_args()

    files = find_slices(args.root, args.experiment, args.sub, args.ses, args.view)
    title = f"sub-{args.sub} | ses-{args.ses} | {args.experiment} | {args.view}"
    fig = plot_slices(files, title, rotate=not args.no_rotate)

    out_dir = args.root / args.experiment / f"sub-{args.sub}" / f"ses-{args.ses}" / "anat"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"sub-{args.sub}_ses-{args.ses}_view-{args.view}_qc.png"
    fig.savefig(out, dpi=150)
    print(f"Saved into: {out}")


if __name__ == "__main__":
    main()